static void uartPrintf(const char *fmt, ...)
{
    char buf[128];
    va_list args;
    va_start(args, fmt);
    vsnprintf(buf, sizeof(buf), fmt, args);
    va_end(args);
    uartSend(buf);
}

static void ledSet()
{
    uint32_t now = HAL_GetTick();
    uint32_t duration = now - ledStateStartTick;

    if (ledState) {
        uartPrintf("LED ON TIME %lu\r\n", (unsigned long)duration);
    } else {
        uartPrintf("LED OFF TIME %lu\r\n", (unsigned long)duration);
    }

    ledStateStartTick = now;
    BSP_LED_Toggle(LED4);
    ledState = !ledState;
    __HAL_TIM_SET_AUTORELOAD(&htim3, ledTime[ledState]);
    __HAL_TIM_SET_COUNTER(&htim3, 0);
    uartPrintf("LED %s\r\n", ledState ? "ON" : "OFF");
}

static void processButton(void)
{
	uint32_t now = HAL_GetTick();


    if (BSP_PB_GetState(BUTTON_KEY) == SET)
    {
        if (press_handled ||  (now - buttonLastEventTick) < BUTTON_DEBOUNCE_MS) {
            return;
        }
        press_handled = true;
        buttonPressStartTick = now;

        if (press_index < 2) {
        	ledSet();
        }
        uartSend("BUTTON ON\r\n");
    }
    else
    {
        if (!press_handled) {
            return;
        }

        if (press_index > 1) {
        	ledSet();
        }

        buttonLastEventTick = now;
        uint32_t pressDuration = buttonLastEventTick - buttonPressStartTick;
        if (pressDuration > BUTTON_LONG_PRESS_MS) {
        	processAdc();
        	uartPrintf("TEMP %ld\r\n", (long)lastTempC);
        	uartPrintf("VCC %lu\r\n", (unsigned long)lastVccMv);
        }
        uartSend("BUTTON OFF\r\n");
        uartPrintf("BUTTON TIME %lu\r\n", (unsigned long)pressDuration);
        press_handled = false;
        press_index++;
        if (press_index >= 4) {
            press_index = 0;
        }
    }
}

static void processAdc(void)
{
    uint32_t sum_temp = 0, sum_vref = 0;
    for (int i = 0; i < 10; i++) {
        sum_temp += temp_array[i];
        sum_vref += vref_array[i];
    }
    uint32_t avg_temp = sum_temp / 10;
    uint32_t avg_vref = sum_vref / 10;

    lastVccMv = (VREFINT_CAL_VREF * (*VREFINT_CAL_ADDR)) / avg_vref;

    lastTempC = (avg_temp - (*TEMPSENSOR_CAL1_ADDR)) *
    		(TEMPSENSOR_CAL2_TEMP - TEMPSENSOR_CAL1_TEMP) /
			((*TEMPSENSOR_CAL2_ADDR) - (*TEMPSENSOR_CAL1_ADDR)) + TEMPSENSOR_CAL1_TEMP;
}

static void processUartCommand(void)
{
    if (uartRxBuf[0] == '?' && uartRxBuf[1] == '\0') {
    	processAdc();
        uartPrintf("VCC %lu\r\n", (unsigned long)lastVccMv);
        uartPrintf("TEMP %ld\r\n", (long)lastTempC);
        uartPrintf("LED %luL\r\n", (unsigned long)ledTime[1]);
        uartPrintf("LED %luD\r\n", (unsigned long)ledTime[0]);
        return;
    }

    if (uartRxIndex >= 2) {
        char suffix = uartRxBuf[uartRxIndex - 1];
        if (suffix == 'L' || suffix == 'D') {
            bool digitsOk = true;
            for (size_t i = 0; i < uartRxIndex - 1; ++i) {
                if (!isdigit((unsigned char)uartRxBuf[i])) {
                    digitsOk = false;
                    break;
                }
            }
            if (digitsOk) {
                long val = strtol(uartRxBuf, NULL, 10);
                if (val >= (long)LED_TIME_MIN && val <= (long)LED_TIME_MAX) {
                    if (suffix == 'L') {
                    	ledTime[1] = (uint32_t)val;
                        uartPrintf("LED %luL OK\r\n", (unsigned long)ledTime[1]);
                    } else {
                    	ledTime[0] = (uint32_t)val;
                        uartPrintf("LED %luD OK\r\n", (unsigned long)ledTime[0]);
                    }
                    return;
                }
            }
        }
    }

    uartSend("ERROR\r\n");
}

void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
    if (huart->Instance == USART2) {
        if (rxByte == '\n' || rxByte == '\r') {
            if (uartRxIndex > 0) {
            	uartRxBuf[uartRxIndex] = '\0';
            	processUartCommand();
            	uartRxIndex = 0;
            }
        } else {
            if (uartRxIndex < sizeof(uartRxBuf) - 1) {
                uartRxBuf[uartRxIndex++] = (char)rxByte;
            } else {
                uartRxIndex = 0;
            }
        }
        HAL_UART_Receive_IT(&huart2, &rxByte, 1);
    }
}
